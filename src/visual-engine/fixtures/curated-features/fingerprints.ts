export interface FeatureFingerprint {
  id: string;
  name: string;
  purpose:
    | "product-capability"
    | "workflow"
    | "trust"
    | "comparison"
    | "technical"
    | "integration"
    | "process"
    | "proof"
    | "education"
    | "conversion"
    | "data"
    | "navigation"
    | "enterprise"
    | "custom";
  layoutFamily: string;
  alignment: string;
  gridPattern: string;
  mediaPlacement: string;
  contentHierarchy: string;
  dominantElement: string;
  interactionModel: string;
  ctaPattern: string;
  density: "ultra-sparse" | "sparse" | "balanced" | "dense" | "ultra-dense";
  visualFamily: string;
  colorDirection: string;
  requiresCapability?: boolean;
}

export type FeatureStructuralDimension =
  | "layoutFamily"
  | "alignment"
  | "gridPattern"
  | "mediaPlacement"
  | "contentHierarchy"
  | "dominantElement"
  | "interactionModel"
  | "ctaPattern"
  | "density";

export const FEATURE_STRUCTURAL_DIMENSIONS: FeatureStructuralDimension[] = [
  "layoutFamily",
  "alignment",
  "gridPattern",
  "mediaPlacement",
  "contentHierarchy",
  "dominantElement",
  "interactionModel",
  "ctaPattern",
  "density",
];

export interface FeatureOverlapComparison {
  featureA: string;
  featureB: string;
  overlappingDimensions: FeatureStructuralDimension[];
  overlapCount: number;
  exceedsThreshold: boolean;
}

export function compareFeatureFingerprints(
  a: FeatureFingerprint,
  b: FeatureFingerprint,
): FeatureOverlapComparison {
  const overlappingDimensions = FEATURE_STRUCTURAL_DIMENSIONS.filter(
    (dim) => a[dim] === b[dim],
  );
  return {
    featureA: a.id,
    featureB: b.id,
    overlappingDimensions,
    overlapCount: overlappingDimensions.length,
    exceedsThreshold: overlappingDimensions.length >= 4,
  };
}

export function checkAllFeatureCollisions(
  fingerprints: FeatureFingerprint[],
): FeatureOverlapComparison[] {
  const collisions: FeatureOverlapComparison[] = [];
  for (let i = 0; i < fingerprints.length; i++) {
    for (let j = i + 1; j < fingerprints.length; j++) {
      const result = compareFeatureFingerprints(fingerprints[i], fingerprints[j]);
      if (result.exceedsThreshold) {
        collisions.push(result);
      }
    }
  }
  return collisions;
}

