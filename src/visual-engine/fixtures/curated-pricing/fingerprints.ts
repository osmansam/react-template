/**
 * OZMI PRICING DIVERSITY FINGERPRINTS & COLLISION VERIFICATION
 *
 * Guarantees zero structural collisions (< 4 matching dimensions)
 * across all pairs of templates in the 50-template Pricing Library.
 */

export interface PricingFingerprint {
  id: string;
  name: string;
  pricingModel: string;
  layoutFamily: string;
  planCount: number;
  gridPattern: string;
  priceHierarchy: string;
  featurePresentation: string;
  ctaPattern: string;
  billingInteraction: string;
  proofPattern: string;
  density: "airy" | "spacious" | "balanced" | "compact" | "dense";

  // Selection & Jev metadata
  category?: "pricing";
  purposes: string[];
  designFamily: string;
  audienceFit: string[];
  industryFit: string[];
  visualIntensity: "subtle" | "moderate" | "high" | "bold";
  colorDirection: string;
  recommendedPlan: boolean;
  capabilities: string[];
  requiresCapability?: boolean;
}

export type PricingStructuralDimension =
  | "pricingModel"
  | "layoutFamily"
  | "planCount"
  | "gridPattern"
  | "priceHierarchy"
  | "featurePresentation"
  | "ctaPattern"
  | "billingInteraction"
  | "proofPattern"
  | "density";

export const PRICING_STRUCTURAL_DIMENSIONS: PricingStructuralDimension[] = [
  "pricingModel",
  "layoutFamily",
  "planCount",
  "gridPattern",
  "priceHierarchy",
  "featurePresentation",
  "ctaPattern",
  "billingInteraction",
  "proofPattern",
  "density",
];

export interface PricingOverlapComparison {
  templateA: string;
  templateB: string;
  overlappingDimensions: PricingStructuralDimension[];
  overlapCount: number;
  isCollision: boolean;
}

/**
 * Checks overlap between two pricing fingerprints across the 10 structural dimensions.
 * A collision occurs when overlapCount >= 4.
 */
export function comparePricingPair(
  a: PricingFingerprint,
  b: PricingFingerprint,
): PricingOverlapComparison {
  const overlappingDimensions: PricingStructuralDimension[] = [];

  for (const dim of PRICING_STRUCTURAL_DIMENSIONS) {
    if (a[dim] === b[dim]) {
      overlappingDimensions.push(dim);
    }
  }

  return {
    templateA: a.id,
    templateB: b.id,
    overlappingDimensions,
    overlapCount: overlappingDimensions.length,
    isCollision: overlappingDimensions.length >= 4,
  };
}

/**
 * Audits all pairwise combinations in an array of fingerprints.
 * Returns any collision where overlapCount >= 4.
 */
export function checkAllPricingCollisions(
  fingerprints: PricingFingerprint[],
): PricingOverlapComparison[] {
  const collisions: PricingOverlapComparison[] = [];

  for (let i = 0; i < fingerprints.length; i++) {
    for (let j = i + 1; j < fingerprints.length; j++) {
      const comparison = comparePricingPair(fingerprints[i], fingerprints[j]);
      if (comparison.isCollision) {
        collisions.push(comparison);
      }
    }
  }

  return collisions;
}

