/**
 * OZMI TESTIMONIAL DIVERSITY FINGERPRINTS & COLLISION VERIFICATION
 *
 * Guarantees zero structural collisions (< 4 matching dimensions)
 * across all pairs of templates in the 40-template Testimonial Library.
 */

export interface TestimonialFingerprint {
  id: string;
  name: string;
  layoutFamily: string;
  alignment: string;
  gridPattern: string;
  testimonialCount: number;
  quoteHierarchy: string;
  authorTreatment: string;
  mediaTreatment: string;
  proofPattern: string;
  interactionModel: string;
  density: "airy" | "spacious" | "balanced" | "compact" | "dense";
  
  // Selection & Jev metadata
  purposes: string[];
  designFamily: string;
  audienceFit: string[];
  industryFit: string[];
  visualIntensity: "subtle" | "moderate" | "high" | "bold";
  colorDirection: string;
  mediaRequirement: string;
  ratingUsage: "none" | "stars";
  capabilities: string[];
  requiresCapability?: boolean;
}

export type TestimonialStructuralDimension =
  | "layoutFamily"
  | "alignment"
  | "gridPattern"
  | "testimonialCount"
  | "quoteHierarchy"
  | "authorTreatment"
  | "mediaTreatment"
  | "proofPattern"
  | "interactionModel"
  | "density";

export const TESTIMONIAL_STRUCTURAL_DIMENSIONS: TestimonialStructuralDimension[] = [
  "layoutFamily",
  "alignment",
  "gridPattern",
  "testimonialCount",
  "quoteHierarchy",
  "authorTreatment",
  "mediaTreatment",
  "proofPattern",
  "interactionModel",
  "density",
];

export interface TestimonialOverlapComparison {
  templateA: string;
  templateB: string;
  overlappingDimensions: TestimonialStructuralDimension[];
  overlapCount: number;
  isCollision: boolean;
}

/**
 * Checks overlap between two testimonial fingerprints across the 10 structural dimensions.
 * A collision occurs when overlapCount >= 4.
 */
export function compareTestimonialPair(
  a: TestimonialFingerprint,
  b: TestimonialFingerprint,
): TestimonialOverlapComparison {
  const overlappingDimensions: TestimonialStructuralDimension[] = [];

  for (const dim of TESTIMONIAL_STRUCTURAL_DIMENSIONS) {
    if (a[dim] === b[dim]) {
      overlappingDimensions.push(dim);
    }
  }

  return {
    templateA: a.id,
    templateB: b.id,
    overlappingDimensions,
    overlapCount: overlappingDimensions.length,
    isCollision: overlappingDimensions.length >= 4,
  };
}

/**
 * Audits all pairwise combinations in an array of fingerprints.
 * Returns any collision where overlapCount >= 4.
 */
export function checkAllTestimonialCollisions(
  fingerprints: TestimonialFingerprint[],
): TestimonialOverlapComparison[] {
  const collisions: TestimonialOverlapComparison[] = [];

  for (let i = 0; i < fingerprints.length; i++) {
    for (let j = i + 1; j < fingerprints.length; j++) {
      const comparison = compareTestimonialPair(fingerprints[i], fingerprints[j]);
      if (comparison.isCollision) {
        collisions.push(comparison);
      }
    }
  }

  return collisions;
}

