export interface PracticeFingerprint {
  id: string;
  name: string;
  category:
    | "contact"
    | "profile"
    | "areas"
    | "property"
    | "maritime"
    | "residency"
    | "evaluation"
    | "hotel-compliance"
    | "gastronomy"
    | "zoning"
    | "watersports"
    | "expat-life"
    | "tenancy"
    | "hotel-m-and-a"
    | "corporate-tax"
    | "dispute-adr"
    | "vip-concierge";
  layoutFamily: string;
  alignment: string;
  gridPattern: string;
  mediaPlacement: string;
  contentHierarchy: string;
  dominantElement: string;
  interactionModel: string;
  ctaPattern: string;
  density: "ultra-sparse" | "sparse" | "balanced" | "dense" | "ultra-dense";
  visualFamily: string;
  colorDirection: string;
}

export type PracticeStructuralDimension =
  | "layoutFamily"
  | "alignment"
  | "gridPattern"
  | "mediaPlacement"
  | "contentHierarchy"
  | "dominantElement"
  | "interactionModel"
  | "ctaPattern"
  | "density";

export const PRACTICE_STRUCTURAL_DIMENSIONS: PracticeStructuralDimension[] = [
  "layoutFamily",
  "alignment",
  "gridPattern",
  "mediaPlacement",
  "contentHierarchy",
  "dominantElement",
  "interactionModel",
  "ctaPattern",
  "density",
];

export interface PracticeOverlapComparison {
  featureA: string;
  featureB: string;
  overlappingDimensions: PracticeStructuralDimension[];
  overlapCount: number;
  exceedsThreshold: boolean;
}

export function comparePracticeFingerprints(
  a: PracticeFingerprint,
  b: PracticeFingerprint,
): PracticeOverlapComparison {
  const overlappingDimensions = PRACTICE_STRUCTURAL_DIMENSIONS.filter(
    (dim) => a[dim] === b[dim],
  );
  return {
    featureA: a.id,
    featureB: b.id,
    overlappingDimensions,
    overlapCount: overlappingDimensions.length,
    exceedsThreshold: overlappingDimensions.length >= 4,
  };
}

export function checkAllPracticeCollisions(
  fingerprints: PracticeFingerprint[],
): PracticeOverlapComparison[] {
  const collisions: PracticeOverlapComparison[] = [];
  for (let i = 0; i < fingerprints.length; i++) {
    for (let j = i + 1; j < fingerprints.length; j++) {
      const result = comparePracticeFingerprints(fingerprints[i], fingerprints[j]);
      if (result.exceedsThreshold) {
        collisions.push(result);
      }
    }
  }
  return collisions;
}

