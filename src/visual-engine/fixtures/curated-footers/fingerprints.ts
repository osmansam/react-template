export interface FooterFingerprint {
  id: string;
  name: string;
  footerModel: string;
  columnLayout: string;
  brandPresence: string;
  newsletterStrategy: string;
  linkArchitecture: string;
  utilityBadges: string;
  mobileTopology: string;
  density: "dense" | "balanced" | "spacious" | "airy" | "compact";
  visualSurface: string;
  heightProfile: string;
  purposes: string[];
  designFamily: string;
  audienceFit: string[];
  industryFit: string[];
  visualIntensity: "subtle" | "moderate" | "bold" | "high";
  colorDirection: string;
  capabilities: string[];
}

export const FOOTER_FINGERPRINT_DIMENSIONS: (keyof FooterFingerprint)[] = [
  "footerModel",
  "columnLayout",
  "brandPresence",
  "newsletterStrategy",
  "linkArchitecture",
  "utilityBadges",
  "mobileTopology",
  "density",
  "visualSurface",
  "heightProfile",
];

export interface FooterCollisionResult {
  a: string;
  b: string;
  matches: string[];
  matchCount: number;
}

export function checkFooterCollisions(
  fingerprints: FooterFingerprint[],
  threshold = 4,
): FooterCollisionResult[] {
  const collisions: FooterCollisionResult[] = [];
  for (let i = 0; i < fingerprints.length; i++) {
    for (let j = i + 1; j < fingerprints.length; j++) {
      const a = fingerprints[i];
      const b = fingerprints[j];
      const matches: string[] = [];
      for (const dim of FOOTER_FINGERPRINT_DIMENSIONS) {
        if (a[dim] === b[dim]) {
          matches.push(dim);
        }
      }
      if (matches.length >= threshold) {
        collisions.push({
          a: a.id,
          b: b.id,
          matches,
          matchCount: matches.length,
        });
      }
    }
  }
  return collisions;
}

export function checkAllFooterCollisions(fingerprints: FooterFingerprint[]): FooterCollisionResult[] {
  return checkFooterCollisions(fingerprints, 4);
}

